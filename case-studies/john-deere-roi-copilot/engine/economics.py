"""Per-acre revenue and operating cost for a farm.

**Two sources, because they measure different things — both are cited on every
result this module returns.**

* **Herbicide: ISU Ag Decision Maker A1-20 (FM 1712), *Estimated Costs of Crop
  Production in Iowa — 2026*, revised January 2026.** Iowa-specific, current,
  and the only anchor available that itemises herbicide separately from the rest
  of crop protection *and* varies it by tillage: corn $56/acre conventional
  against $83 strip- or low-till, soybeans $75 against $89. Tillage substitutes
  for chemical weed control, so this is not a rounding difference. Archived at
  `data/reference/isu_a1_20_2026.json`; the PDF is alongside it because
  extension.iastate.edu serves a proof-of-work bot challenge to scripted clients.

* **Everything else: USDA ERS Commodity Costs and Returns, Heartland region**,
  from `data/raw/ers/commodity_budgets.parquet` (generated by `etl/ers.py`).
  Fertilizer, seed, fuel, repairs, custom services, interest and allocated
  overhead. Heartland is the finest geographic cut ERS publishes; there is no
  county resolution and none is synthesised.

**The two disagree, and the disagreement decides the project's headline.** ISU
conventional corn herbicide alone ($56.00) exceeds the entire ERS Heartland 2025
`Chemicals` line ($49.23), and is 134% of the ERS-derived herbicide figure
($41.85). Neither is wrong: ERS surveys realised expenditure — growers buy on
program discounts, use generics, cut rates and skip passes — while ISU prices a
complete, agronomically defensible program at surveyed input prices. See
`deliverables/appendix/assumptions.md` §2 and §6.

So the anchor is **swappable**. `CostAnchor.ISU_A1_20` is the Iowa default;
`CostAnchor.ERS_DERIVED` splits herbicide out of the ERS `Chemicals` line using
the measured herbicide share from `data/priors/crop_protection_split.json`
(0.85 corn, 0.84 soybeans). Every `CropEconomics` records which one produced it.

No I/O: parquet and JSON are read at the boundary and arrive as `CropBudget`.
"""

from __future__ import annotations

from enum import StrEnum

from engine.models import (
    Crop,
    Farm,
    FrozenModel,
    NonNegative,
    Tillage,
    UnitInterval,
)


class CostAnchor(StrEnum):
    """Which source sets the herbicide line.

    The rest of the budget is ERS either way. This choice moves corn herbicide
    from $41.85/acre to $56.00 — a 34% swing on the number See & Spray's savings
    are computed against, and therefore on whether the machine pays.
    """

    #: ISU A1-20 2026, selected by tillage. Prescriptive program cost, Iowa.
    ISU_A1_20 = "isu_a1_20"
    #: ERS `Chemicals` x herbicide share. Realised survey spending, Heartland.
    ERS_DERIVED = "ers_derived"


class CropBudget(FrozenModel):
    """One crop's per-acre budget, assembled at the I/O boundary.

    ERS lines are Heartland, `dollars per planted acre`. `isu_herbicide_usd_per_acre`
    carries one entry per tillage system the farm might use; a missing entry
    raises rather than falling back, because a silent default here would price
    a strip-till farm at conventional-tillage herbicide cost.
    """

    crop: Crop
    yield_bu_per_acre: NonNegative
    #: ERS `Operating costs` / `Chemicals` — herbicide + insecticide + fungicide.
    ers_chemicals_usd_per_acre: NonNegative
    #: Herbicide share of that line. `crop_protection_split.json`, §3 of assumptions.
    ers_herbicide_share: UnitInterval
    #: ERS `Total, operating costs` less `Chemicals`.
    ers_operating_ex_chemicals_usd_per_acre: NonNegative
    #: ERS `Total, allocated overhead`, including the opportunity cost of land.
    ers_overhead_usd_per_acre: NonNegative
    isu_herbicide_usd_per_acre: dict[Tillage, NonNegative]


class CropEconomics(FrozenModel):
    """Costed-out per-acre economics for one crop on one farm.

    Sources: herbicide per `herbicide_anchor` (ISU A1-20 2026 or USDA ERS
    Commodity Costs and Returns, Heartland); every other line USDA ERS
    Heartland. See the module docstring for why both are named.
    """

    crop: Crop
    acres: NonNegative
    tillage: Tillage
    herbicide_anchor: CostAnchor
    yield_bu_per_acre: NonNegative
    price_usd_per_bu: NonNegative
    revenue_usd_per_acre: NonNegative
    herbicide_usd_per_acre: NonNegative
    non_herbicide_chemicals_usd_per_acre: NonNegative
    other_operating_usd_per_acre: NonNegative
    overhead_usd_per_acre: NonNegative
    operating_cost_usd_per_acre: NonNegative
    total_cost_usd_per_acre: NonNegative

    @property
    def net_usd_per_acre(self) -> float:
        """Revenue less total costs listed.

        Negative is normal — ERS reports Heartland corn at -$108.05/acre for 2025.
        """
        return self.revenue_usd_per_acre - self.total_cost_usd_per_acre


class FarmEconomics(FrozenModel):
    """Whole-farm roll-up. Every total is acre-weighted, never a plain mean."""

    farm_name: str
    herbicide_anchor: CostAnchor
    crops: tuple[CropEconomics, ...]

    @property
    def total_acres(self) -> float:
        """Sum of crop acres."""
        return sum(row.acres for row in self.crops)

    @property
    def revenue_usd(self) -> float:
        """Gross value of production across the farm."""
        return sum(row.revenue_usd_per_acre * row.acres for row in self.crops)

    @property
    def operating_cost_usd(self) -> float:
        """Operating costs across the farm."""
        return sum(row.operating_cost_usd_per_acre * row.acres for row in self.crops)

    @property
    def total_cost_usd(self) -> float:
        """Operating plus allocated overhead, across the farm."""
        return sum(row.total_cost_usd_per_acre * row.acres for row in self.crops)

    @property
    def net_usd(self) -> float:
        """Revenue less total costs listed, across the farm."""
        return self.revenue_usd - self.total_cost_usd

    @property
    def herbicide_usd_per_acre(self) -> float:
        """Acre-weighted herbicide spend — the number See & Spray works against."""
        acres = self.total_acres
        if acres == 0.0:
            return 0.0
        return sum(row.herbicide_usd_per_acre * row.acres for row in self.crops) / acres


def herbicide_usd_per_acre(
    budget: CropBudget, tillage: Tillage, anchor: CostAnchor
) -> float:
    """Herbicide spend per acre, from whichever source the anchor names.

    Args:
        budget: The crop's budget lines.
        tillage: The farm's tillage system. Only the ISU anchor varies with it —
            ERS publishes no tillage breakdown.
        anchor: Which source to believe.

    Returns:
        Dollars per planted acre of herbicide, excluding insecticide and fungicide.

    Raises:
        ValueError: If the ISU anchor is selected and the budget carries no row
            for `tillage`. Defaulting here would price reduced tillage at the
            conventional figure, understating it by up to 48%.
    """
    if anchor is CostAnchor.ERS_DERIVED:
        return budget.ers_chemicals_usd_per_acre * budget.ers_herbicide_share
    try:
        return budget.isu_herbicide_usd_per_acre[tillage]
    except KeyError:
        raise ValueError(
            f"ISU A1-20 budget for {budget.crop.value} has no {tillage.value} row; "
            f"available: {sorted(t.value for t in budget.isu_herbicide_usd_per_acre)}"
        ) from None


def crop_economics(
    *,
    budget: CropBudget,
    acres: float,
    price_usd_per_bu: float,
    tillage: Tillage,
    anchor: CostAnchor,
) -> CropEconomics:
    """Per-acre revenue and cost for one crop.

    Args:
        budget: ERS lines plus the ISU herbicide rows.
        acres: Acres of this crop.
        price_usd_per_bu: Farm-gate price.
        tillage: The farm's tillage system.
        anchor: Which source sets the herbicide line.

    Returns:
        A `CropEconomics`. Non-herbicide chemicals are always the ERS remainder
        `chemicals x (1 - herbicide_share)`, so swapping the anchor moves the
        herbicide line and nothing else.
    """
    herbicide = herbicide_usd_per_acre(budget, tillage, anchor)
    non_herbicide = budget.ers_chemicals_usd_per_acre * (1.0 - budget.ers_herbicide_share)
    operating = herbicide + non_herbicide + budget.ers_operating_ex_chemicals_usd_per_acre
    return CropEconomics(
        crop=budget.crop,
        acres=acres,
        tillage=tillage,
        herbicide_anchor=anchor,
        yield_bu_per_acre=budget.yield_bu_per_acre,
        price_usd_per_bu=price_usd_per_bu,
        revenue_usd_per_acre=budget.yield_bu_per_acre * price_usd_per_bu,
        herbicide_usd_per_acre=herbicide,
        non_herbicide_chemicals_usd_per_acre=non_herbicide,
        other_operating_usd_per_acre=budget.ers_operating_ex_chemicals_usd_per_acre,
        overhead_usd_per_acre=budget.ers_overhead_usd_per_acre,
        operating_cost_usd_per_acre=operating,
        total_cost_usd_per_acre=operating + budget.ers_overhead_usd_per_acre,
    )


def farm_economics(
    farm: Farm,
    budgets: dict[Crop, CropBudget],
    prices_usd_per_bu: dict[Crop, float],
    *,
    anchor: CostAnchor = CostAnchor.ISU_A1_20,
) -> FarmEconomics:
    """Roll per-crop economics up to the farm.

    Args:
        farm: Supplies the acreage mix and the tillage system.
        budgets: One `CropBudget` per crop the farm grows.
        prices_usd_per_bu: One price per crop the farm grows.
        anchor: Which source sets the herbicide line. Defaults to ISU A1-20,
            the Iowa-specific figure.

    Returns:
        A `FarmEconomics` whose totals are acre-weighted.

    Raises:
        ValueError: If a crop the farm grows has no budget or no price. Skipping
            it would quietly shrink the farm.
    """
    missing = [
        row.crop.value
        for row in farm.acreage
        if row.crop not in budgets or row.crop not in prices_usd_per_bu
    ]
    if missing:
        raise ValueError(f"no budget or price for crops the farm grows: {sorted(missing)}")
    return FarmEconomics(
        farm_name=farm.name,
        herbicide_anchor=anchor,
        crops=tuple(
            crop_economics(
                budget=budgets[row.crop],
                acres=row.acres,
                price_usd_per_bu=prices_usd_per_bu[row.crop],
                tillage=farm.tillage,
                anchor=anchor,
            )
            for row in farm.acreage
        ),
    )
