"""End-to-end: the 2,400-acre Story County demo farm, base sprayer vs Premium.

This is the file that proves the engine is wired to real data rather than to
constants that happen to agree with it. Everything is loaded here, at the
boundary — the ERS parquet, the ISU A1-20 reference JSON, the crop-protection
priors — and passed into the engine as models. `engine/` itself never touches a
file, which is what will make a golden-file test possible.

The scenario: 1,200 acres corn and 1,200 acres soybeans, conventional tillage,
two herbicide passes a year, upgrading a $650,000 base sprayer to a $750,000
See & Spray Premium. Run with `-s` to print the worked example.

The assertions deliberately pin *directions and orders of magnitude*, not
digits. The digits move with the input files; the finding must not.
"""

from __future__ import annotations

import json
from pathlib import Path

import polars as pl
import pytest
from engine.economics import CostAnchor, CropBudget, farm_economics
from engine.finance import annuity_factor, break_even_acreage, npv
from engine.machinery import (
    MachineryRates,
    field_capacity_acres_per_hour,
    hours_for_acres,
    machinery_cost,
)
from engine.models import Crop, CropAcreage, Farm, Machine, Scenario, SprayerConfig, Tillage
from engine.precision import (
    UADA_TREATED_AREA,
    HerbicideProgram,
    break_even_targeted_herbicide_usd_per_acre,
    crop_savings,
)

CASE_ROOT = Path(__file__).resolve().parents[1]
ERS_PARQUET = CASE_ROOT / "data" / "raw" / "ers" / "commodity_budgets.parquet"
PRIORS = CASE_ROOT / "data" / "priors" / "crop_protection_split.json"
ISU = CASE_ROOT / "data" / "reference" / "isu_a1_20_2026.json"

COST_YEAR = 2025
REGION = "Heartland"
#: Iowa corn and soybean programs are a broadcast PRE plus a POST. UNL #016,
#: #059 and #060 (assumptions.md §4.3) all price exactly two herbicide passes.
HERBICIDE_PASSES_PER_YEAR = 2
#: See & Spray runs on the foliar POST pass; the PRE is broadcast residual.
ADDRESSABLE_PASSES_PER_YEAR = 1

_ISU_TILLAGE = {
    "conventional": Tillage.CONVENTIONAL,
    "strip-till": Tillage.STRIP_TILL,
    "low-till": Tillage.LOW_TILL,
    "low-till, drilled": Tillage.LOW_TILL,
}
_PRIOR_KEY = {Crop.CORN: "corn", Crop.SOYBEANS: "soybeans"}
_ERS_SOURCE = {Crop.CORN: "corn", Crop.SOYBEANS: "soybeans"}


# --- Boundary: load the published data ---------------------------------------


def _ers_lines(frame: pl.DataFrame, crop: Crop) -> dict[str, float]:
    rows = frame.filter(
        (pl.col("source") == _ERS_SOURCE[crop])
        & (pl.col("region") == REGION)
        & (pl.col("year") == COST_YEAR)
    )
    return dict(zip(rows["item"].to_list(), rows["value"].to_list(), strict=True))


def _isu_herbicide(isu: dict, crop: Crop) -> dict[Tillage, float]:
    """Herbicide by tillage for the rotation budgets, ISU A1-20 2026."""
    name = "corn" if crop is Crop.CORN else "soybeans"
    out: dict[Tillage, float] = {}
    for row in isu["budgets"]:
        tillage = _ISU_TILLAGE.get(row.get("tillage", "").split(" (")[0])
        if row["crop"] != name or tillage is None or "herbicide" not in row:
            continue
        # Continuous corn is a different rotation; the demo farm rotates.
        if row.get("rotation") == "continuous corn":
            continue
        out.setdefault(tillage, float(row["herbicide"]))
    return out


def _budget(frame: pl.DataFrame, priors: dict, isu: dict, crop: Crop) -> CropBudget:
    ers = _ers_lines(frame, crop)
    prior = priors["crops"][_PRIOR_KEY[crop]]
    return CropBudget(
        crop=crop,
        yield_bu_per_acre=ers["Yield"],
        ers_chemicals_usd_per_acre=ers["Chemicals"],
        ers_herbicide_share=prior["herbicide_share"]["mode"],
        ers_operating_ex_chemicals_usd_per_acre=ers["Total, operating costs"] - ers["Chemicals"],
        ers_overhead_usd_per_acre=ers["Total, allocated overhead"],
        isu_herbicide_usd_per_acre=_isu_herbicide(isu, crop),
    )


@pytest.fixture(scope="module")
def inputs() -> dict:
    """Everything the engine needs, read once at the boundary."""
    if not ERS_PARQUET.exists():  # pragma: no cover - generated by etl/ers.py
        pytest.skip(f"{ERS_PARQUET} missing; run etl.ers.extract first")
    frame = pl.read_parquet(ERS_PARQUET)
    priors = json.loads(PRIORS.read_text())
    isu = json.loads(ISU.read_text())
    return {
        "budgets": {c: _budget(frame, priors, isu, c) for c in (Crop.CORN, Crop.SOYBEANS)},
        "priors": priors,
        "prices": {
            c: _ers_lines(frame, c)["Price"] for c in (Crop.CORN, Crop.SOYBEANS)
        },
        "programs": {
            c: HerbicideProgram(
                crop=c,
                addressable_share=priors["crops"][_PRIOR_KEY[c]]["addressable_share"]["mode"],
                # Werle 2024: residuals consolidated into a broadcast PRE, clean
                # foliar POST. The optimistic case for a single-tank Premium.
                residual_free_tank_share=1.0,
            )
            for c in (Crop.CORN, Crop.SOYBEANS)
        },
    }


# --- The scenario ------------------------------------------------------------

FARM = Farm(
    name="Story County demo",
    state="IA",
    county_fips="19169",
    tillage=Tillage.CONVENTIONAL,
    acreage=[
        CropAcreage(crop=Crop.CORN, acres=1200.0),
        CropAcreage(crop=Crop.SOYBEANS, acres=1200.0),
    ],
)
BASE = Machine(
    name="base self-propelled sprayer",
    config=SprayerConfig.BASE,
    purchase_price_usd=650_000.0,
    working_speed_mph=18.0,
    boom_width_ft=120.0,
    field_efficiency=0.75,
    useful_life_years=10,
    annual_use_hours=400.0,
)
PREMIUM = BASE.model_copy(
    update={
        "name": "See & Spray Premium",
        "config": SprayerConfig.PREMIUM,
        "purchase_price_usd": 750_000.0,
        "working_speed_mph": 12.0,
        "subscription_usd_per_acre": 5.0,
    }
)
RATES = MachineryRates(
    interest_rate=0.07,
    # Not sourced in this repository. Fuel is under $0.50/acre for a sprayer at
    # any plausible value, so the result is insensitive to both of these.
    engine_pto_hp=400.0,
    diesel_usd_per_gal=3.50,
    labour_usd_per_hour=20.40,  # ISU A1-20 2026 wage rate
)
DISCOUNT_RATE = 0.07
HORIZON_YEARS = 10


def _incremental_annual_operating_usd(acres_farmed: float) -> float:
    """Extra cash cost per year of running Premium instead of base.

    Excludes depreciation and interest — those are the capital outlay, which the
    NPV already carries at t=0. Counting them here as well would charge the
    machine twice, the most common way an equipment case is quietly rigged.
    """
    covered = acres_farmed * HERBICIDE_PASSES_PER_YEAR
    out = 0.0
    for machine, sign in ((PREMIUM, 1.0), (BASE, -1.0)):
        cost = machinery_cost(machine, RATES)
        out += sign * (
            cost.operating_usd_per_hour * hours_for_acres(machine, covered)
            + cost.tax_insurance_housing_usd_per_year
        )
    return out


def _annual_net_benefit_usd(inputs: dict, acres_farmed: float, anchor: CostAnchor) -> float:
    """Chemical savings less subscription less the machine's extra running cost."""
    scaled = FARM.model_copy(
        update={
            "acreage": tuple(
                row.model_copy(update={"acres": acres_farmed / 2.0}) for row in FARM.acreage
            )
        }
    )
    economics = farm_economics(scaled, inputs["budgets"], inputs["prices"], anchor=anchor)
    savings = sum(
        crop_savings(
            crop=row.crop,
            acres=row.acres * ADDRESSABLE_PASSES_PER_YEAR,
            herbicide_usd_per_acre=row.herbicide_usd_per_acre,
            program=inputs["programs"][row.crop],
            treated=UADA_TREATED_AREA[row.crop],
            machine=PREMIUM,
        ).annual_net_savings_usd
        for row in economics.crops
    )
    return savings - _incremental_annual_operating_usd(acres_farmed)


def _npv_at(inputs: dict, acres_farmed: float, anchor: CostAnchor) -> float:
    """NPV of the upgrade if the farm were `acres_farmed` acres."""
    incremental_capital = PREMIUM.purchase_price_usd - BASE.purchase_price_usd
    salvage = incremental_capital * PREMIUM.salvage_fraction
    flows = [
        -incremental_capital,
        *([_annual_net_benefit_usd(inputs, acres_farmed, anchor)] * HORIZON_YEARS),
    ]
    flows[-1] += salvage
    return npv(DISCOUNT_RATE, flows)


# --- Tests -------------------------------------------------------------------


def test_the_scenario_is_constructible_from_the_frozen_contract(inputs):
    scenario = Scenario(
        farm=FARM,
        current_machine=BASE,
        proposed_machine=PREMIUM,
        crop_prices_usd_per_bu=inputs["prices"],
        discount_rate=DISCOUNT_RATE,
        horizon_years=HORIZON_YEARS,
    )
    assert scenario.farm.total_acres == 2400.0


def test_isu_and_ers_anchors_disagree_by_more_than_a_third(inputs):
    isu = farm_economics(FARM, inputs["budgets"], inputs["prices"], anchor=CostAnchor.ISU_A1_20)
    ers = farm_economics(
        FARM, inputs["budgets"], inputs["prices"], anchor=CostAnchor.ERS_DERIVED
    )
    assert isu.herbicide_usd_per_acre > ers.herbicide_usd_per_acre * 1.3


def test_the_anchor_flips_the_purchase_decision(inputs):
    """The headline. Which source you believe decides whether the machine pays."""
    assert _npv_at(inputs, 2400.0, CostAnchor.ISU_A1_20) > 0.0
    assert _npv_at(inputs, 2400.0, CostAnchor.ERS_DERIVED) < 0.0


def test_break_even_acreage_zeroes_the_npv(inputs):
    acres = break_even_acreage(lambda a: _npv_at(inputs, a, CostAnchor.ERS_DERIVED))
    assert acres is not None
    assert _npv_at(inputs, acres, CostAnchor.ERS_DERIVED) == pytest.approx(0.0, abs=1.0)
    assert 2_000.0 < acres < 6_000.0


def test_break_even_targeted_herbicide_is_in_the_same_neighbourhood_as_uadas_eleven(inputs):
    """Compare our break-even against UADA's published ~$11/acre targeted.

    At 2,400 acres a year the capital is spread thinner than in their worked
    case, so ours must be higher — but not by a multiple, or the model has gone
    wrong somewhere.
    """
    break_even = _break_even_targeted(inputs, 2400.0)
    assert 11.0 < break_even < 22.0


def _break_even_targeted(inputs: dict, acres_farmed: float) -> float:
    """Targeted herbicide $/acre at which the upgrade exactly pays, UADA-style."""
    incremental_capital = PREMIUM.purchase_price_usd - BASE.purchase_price_usd
    salvage_pv = (
        incremental_capital
        * PREMIUM.salvage_fraction
        / (1.0 + DISCOUNT_RATE) ** HORIZON_YEARS
    )
    annualised_capital = (incremental_capital - salvage_pv) / annuity_factor(
        DISCOUNT_RATE, HORIZON_YEARS
    )
    machine_per_acre = (
        annualised_capital + _incremental_annual_operating_usd(acres_farmed)
    ) / acres_farmed
    unsprayed = sum(
        UADA_TREATED_AREA[row.crop].unsprayed_fraction * row.acres for row in FARM.acreage
    ) / FARM.total_acres
    return break_even_targeted_herbicide_usd_per_acre(
        machine_cost_usd_per_acre=machine_per_acre,
        subscription_usd_per_acre=PREMIUM.subscription_usd_per_acre,
        unsprayed_fraction=unsprayed,
    )


def test_overlapping_residuals_kill_the_case_under_either_anchor(inputs):
    """Standard Iowa waterhemp practice leaves Premium almost nothing to target."""
    constrained = {
        crop: program.model_copy(update={"residual_free_tank_share": 0.268})
        for crop, program in inputs["programs"].items()
    }
    for anchor in CostAnchor:
        assert _npv_at({**inputs, "programs": constrained}, 2400.0, anchor) < 0.0


def test_the_worked_example(inputs, capsys):
    """Print the demo farm end to end. Run with `-s` to read it."""
    lines: list[str] = []
    for anchor in (CostAnchor.ISU_A1_20, CostAnchor.ERS_DERIVED):
        economics = farm_economics(FARM, inputs["budgets"], inputs["prices"], anchor=anchor)
        lines.append(f"\n=== anchor: {anchor.value} ===")
        for row in economics.crops:
            savings = crop_savings(
                crop=row.crop,
                acres=row.acres,
                herbicide_usd_per_acre=row.herbicide_usd_per_acre,
                program=inputs["programs"][row.crop],
                treated=UADA_TREATED_AREA[row.crop],
                machine=PREMIUM,
            )
            lines.append(
                f"  {row.crop.value:<9} herbicide ${row.herbicide_usd_per_acre:6.2f}/ac"
                f"  targeted ${savings.addressable_usd_per_acre:6.2f}/ac"
                f"  gross ${savings.gross_savings_usd_per_acre:5.2f}"
                f"  sub -${savings.subscription_usd_per_acre:4.2f}"
                f"  net ${savings.net_savings_usd_per_acre:6.2f}/ac"
            )
        benefit = _annual_net_benefit_usd(inputs, 2400.0, anchor)
        value = _npv_at(inputs, 2400.0, anchor)
        acres = break_even_acreage(lambda a, k=anchor: _npv_at(inputs, a, k))
        lines.append(f"  annual net benefit  ${benefit:,.0f}/yr")
        lines.append(f"  NPV @7%, 10yr       ${value:,.0f}")
        lines.append(f"  break-even acreage  {acres if acres is None else f'{acres:,.0f} ac/yr'}")
    lines.append(
        f"\n  break-even targeted herbicide  ${_break_even_targeted(inputs, 2400.0):.2f}/ac"
        "   (UADA Premium: ~$11.00/ac)"
    )
    base_cost = machinery_cost(BASE, RATES)
    lines.append(
        f"  base field capacity {field_capacity_acres_per_hour(BASE):.1f} ac/hr, "
        f"Premium {field_capacity_acres_per_hour(PREMIUM):.1f} ac/hr "
        f"({field_capacity_acres_per_hour(PREMIUM) / field_capacity_acres_per_hour(BASE):.1%})"
    )
    lines.append(
        f"  base sprayer at rated 400 h/yr: ${base_cost.total_usd_per_acre:.2f}/ac "
        "(ISU custom rate $10.00/ac)"
    )
    with capsys.disabled():
        print("\n".join(lines))
    assert lines
